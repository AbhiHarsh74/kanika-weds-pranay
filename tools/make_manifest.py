#!/usr/bin/env python3
"""Scan couple_photos/ and write js/couple-photos.js.
GitHub Pages can't list folders, so the site reads this generated list instead.
Run from anywhere:  python tools/make_manifest.py
"""
import json
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent
EXTS = {'.jpg', '.jpeg', '.png', '.webp', '.avif'}

files = sorted(p.name for p in (ROOT / 'couple_photos').iterdir() if p.suffix.lower() in EXTS)
paths = ['couple_photos/' + quote(n) for n in files]

out = ROOT / 'js' / 'couple-photos.js'
out.write_text(
    '// Generated by tools/make_manifest.py - re-run it after adding or removing photos.\n'
    '// (You can also edit this list by hand.)\n'
    'window.COUPLE_PHOTOS = ' + json.dumps(paths, indent=2) + ';\n',
    encoding='utf-8')
print(f'{len(paths)} photos -> {out.relative_to(ROOT)}')
