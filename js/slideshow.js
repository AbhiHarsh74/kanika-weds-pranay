/* "Our story" photo slideshow.
   Photos come from window.COUPLE_PHOTOS (js/couple-photos.js, generated by tools/make_manifest.py).
   Every few seconds a random photo crossfades in over the current one while slowly zooming (Ken Burns). */
(() => {
  const host = document.getElementById('slides');
  if (!host) return;
  const frame = host.parentElement;
  const reduce = matchMedia('(prefers-reduced-motion: reduce)').matches;

  const INTERVAL = 5000;   // ms between photos
  const DURATION = 1600;   // ms for the crossfade
  // Slow zoom (see .slide in style.css) drifts towards one of these points, kept high to favour faces.
  const ORIGINS = ['35% 30%', '65% 30%', '50% 25%', '50% 40%'];

  let photos = (window.COUPLE_PHOTOS || []).slice();
  if (!photos.length && host.dataset.fallback) photos = [host.dataset.fallback];
  if (!photos.length) return;

  // Shuffle bag: every photo is shown once (random order) before any repeats.
  let bag = [], last = null, visible = true;
  function shuffle(a) {
    for (let i = a.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
  }
  function nextPhoto() {
    if (!bag.length) {
      bag = shuffle(photos.slice());
      if (bag.length > 1 && bag[0] === last) bag.push(bag.shift());
    }
    return (last = bag.shift());
  }
  function load(src) {
    return new Promise((resolve) => {
      const img = new Image();
      img.alt = 'Kanika and Pranay';
      img.decoding = 'async';
      img.onload = () => resolve(img);
      img.onerror = () => resolve(null);   // skip broken paths
      img.src = src;
    });
  }

  async function show(first) {
    let img = null;
    for (let tries = 0; !img && tries < photos.length; tries++) img = await load(nextPhoto());
    if (!img) return;
    img.className = 'slide';
    img.style.transformOrigin = ORIGINS[Math.floor(Math.random() * ORIGINS.length)];
    if (first || reduce) {
      host.appendChild(img);
    } else {
      img.style.opacity = '0';
      host.appendChild(img);
      img.getBoundingClientRect();         // commit opacity 0 before animating
      img.style.transition = 'opacity ' + DURATION + 'ms ease-in-out';
      img.style.opacity = '1';
    }
    // once the new photo has landed, remove the ones underneath
    setTimeout(() => { while (host.children.length > 1) host.removeChild(host.firstChild); },
               reduce ? 0 : DURATION + 100);
  }

  new IntersectionObserver(([e]) => { visible = e.isIntersecting; }).observe(frame);

  (async function loop() {
    await show(true);
    if (photos.length < 2) return;
    for (;;) {
      await new Promise((r) => setTimeout(r, INTERVAL));
      if (document.hidden || !visible) continue;   // pause when off-screen
      await show(false);
    }
  })();
})();